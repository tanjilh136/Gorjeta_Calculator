"""Builds MistuGorjetas_Setup.exe (run on Windows).

    python build.py                 # ask for the secret key, build app + installer
    python build.py --keep-key      # rebuild with the key hash already configured
    python build.py --set-key-only  # only (re)configure the key hash, no build
    python build.py --skip-installer

Steps:
  1. Asks for the secret install key (typed twice, hidden) and writes only salted
     hashes: mistu_gorjetas/build_config.py (PBKDF2-HMAC-SHA256, for the app) and
     installer/key_hash.iss (iterated salted SHA-256, for the installer's password
     page). The plain key is never written to disk.
  2. Runs PyInstaller (onedir) -> dist/MistuGorjetas/
  3. Runs Inno Setup (ISCC.exe)  -> dist/MistuGorjetas_Setup.exe
"""

from __future__ import annotations

import argparse
import getpass
import os
import secrets
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from mistu_gorjetas import APP_NAME, VERSION  # noqa: E402
from mistu_gorjetas.licensing import installer_hash_hex, pbkdf2_hex  # noqa: E402

APP_ITERATIONS = 390_000
INSTALLER_ITERATIONS = 20_000
BUILD_CONFIG = ROOT / "mistu_gorjetas" / "build_config.py"
INSTALLER_KEY = ROOT / "installer" / "key_hash.iss"
ISS = ROOT / "installer" / "MistuGorjetas.iss"
DIST = ROOT / "dist"
BUILD = ROOT / "build"


def fail(msg: str) -> None:
    print(f"\nERROR: {msg}")
    sys.exit(1)


# ------------------------------------------------------------------ key
def key_problem(key: str) -> str | None:
    if len(key) < 8:
        return "must be at least 8 characters"
    if not all(32 <= ord(ch) < 127 for ch in key):
        return "only plain ASCII characters are allowed (no accents)"
    if key != key.strip():
        return "no spaces at the start or end"
    return None


def ask_key() -> str:
    # Unattended builds: the key can come from the MISTU_BUILD_KEY environment
    # variable (kept in memory only, never written to disk).
    env_key = os.environ.pop("MISTU_BUILD_KEY", None)
    if env_key is not None:
        problem = key_problem(env_key)
        if problem:
            fail(f"MISTU_BUILD_KEY {problem}")
        print("Using the key from MISTU_BUILD_KEY.")
        return env_key

    print("Enter the secret install key. It is NOT stored anywhere - only a salted hash is.")
    print("Rules: at least 8 characters, plain ASCII (letters, digits, symbols), "
          "no spaces at the start or end.\n")
    while True:
        key = getpass.getpass("Secret key: ")
        problem = key_problem(key)
        if problem:
            print(f"  -> {problem}, try again.")
            continue
        if getpass.getpass("Repeat key: ") != key:
            print("  -> the keys do not match, try again.")
            continue
        return key


def write_key_hashes(key: str) -> None:
    app_salt = secrets.token_hex(16)
    app_hash = pbkdf2_hex(key, app_salt, APP_ITERATIONS)
    BUILD_CONFIG.write_text(
        "# Generated by build.py - do not edit by hand.\n"
        "# Holds only a salted hash of the install key; the key itself is never stored.\n"
        f"KEY_ITERATIONS = {APP_ITERATIONS}\n"
        f'KEY_SALT = "{app_salt}"\n'
        f'KEY_HASH = "{app_hash}"\n',
        encoding="utf-8",
    )
    inst_salt = secrets.token_hex(16)
    inst_hash = installer_hash_hex(key, inst_salt, INSTALLER_ITERATIONS)
    INSTALLER_KEY.write_text(
        "; Generated by build.py - do not edit by hand.\n"
        "; Salted hash of the install key for the installer password page.\n"
        f'#define KeySalt "{inst_salt}"\n'
        f'#define KeyHash "{inst_hash}"\n'
        f"#define KeyIterations {INSTALLER_ITERATIONS}\n",
        encoding="utf-8",
    )
    print(f"Key hashes written to:\n  {BUILD_CONFIG}\n  {INSTALLER_KEY}")


def key_configured() -> bool:
    text = BUILD_CONFIG.read_text(encoding="utf-8") if BUILD_CONFIG.exists() else ""
    inst = INSTALLER_KEY.read_text(encoding="utf-8") if INSTALLER_KEY.exists() else ""
    return 'KEY_HASH = ""' not in text and "KEY_HASH" in text and 'KeyHash ""' not in inst and "KeyHash" in inst


# ------------------------------------------------------------ pyinstaller
def version_tuple() -> tuple[int, int, int, int]:
    parts = [int(p) for p in VERSION.split(".")] + [0, 0, 0, 0]
    return tuple(parts[:4])  # type: ignore[return-value]


def write_version_file() -> Path:
    v = version_tuple()
    path = BUILD / "version_info.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers={v}, prodvers={v}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Optivex Labs'),
      StringStruct('FileDescription', '{APP_NAME}'),
      StringStruct('FileVersion', '{VERSION}'),
      StringStruct('InternalName', 'MistuGorjetas'),
      StringStruct('LegalCopyright', 'Designed by Optivex Labs'),
      StringStruct('OriginalFilename', 'MistuGorjetas.exe'),
      StringStruct('ProductName', '{APP_NAME}'),
      StringStruct('ProductVersion', '{VERSION}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""", encoding="utf-8")
    return path


def run_pyinstaller() -> None:
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        fail("PyInstaller is not installed. Run: pip install -r requirements-build.txt")
    app_dist = DIST / "MistuGorjetas"
    if app_dist.exists():
        shutil.rmtree(app_dist)
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean", "--windowed", "--onedir",
        "--name", "MistuGorjetas",
        "--icon", str(ROOT / "assets" / "app.ico"),
        "--version-file", str(write_version_file()),
        "--add-data", f"{ROOT / 'assets'}{os.pathsep}assets",
        "--distpath", str(DIST),
        "--workpath", str(BUILD / "pyinstaller"),
        "--specpath", str(BUILD),
        "--exclude-module", "tkinter",
        str(ROOT / "run_app.py"),
    ]
    print("\n== PyInstaller ==\n" + " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=ROOT)
    if not (app_dist / "MistuGorjetas.exe").exists() and sys.platform == "win32":
        fail("PyInstaller did not produce dist/MistuGorjetas/MistuGorjetas.exe")


# -------------------------------------------------------------- inno setup
def find_iscc(explicit: str | None) -> Path | None:
    candidates = [explicit, os.environ.get("ISCC")]
    for base in (os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles"),
                 os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs")):
        if base:
            candidates.append(os.path.join(base, "Inno Setup 6", "ISCC.exe"))
    candidates.append(shutil.which("ISCC") or shutil.which("iscc"))
    for c in candidates:
        if c and Path(c).is_file():
            return Path(c)
    return None


def run_inno(iscc_arg: str | None) -> Path:
    iscc = find_iscc(iscc_arg)
    if iscc is None:
        fail("Inno Setup 6 (ISCC.exe) not found. Install it from https://jrsoftware.org/isdl.php "
             "or pass --iscc \"C:\\path\\to\\ISCC.exe\".")
    cmd = [str(iscc), f"/DAppVersion={VERSION}", str(ISS)]
    print("\n== Inno Setup ==\n" + " ".join(cmd))
    out = DIST / "MistuGorjetas_Setup.exe"
    # Antivirus scanners sometimes lock the new Setup.exe while Inno Setup is still
    # writing it ("EndUpdateResource failed"); retrying a moment later works.
    for attempt in range(1, 4):
        if subprocess.run(cmd, cwd=ISS.parent).returncode == 0:
            break
        if attempt == 3:
            fail("Inno Setup failed (see the messages above).")
        print(f"\nInno Setup failed (attempt {attempt}/3) - retrying in 10 seconds...")
        time.sleep(10)
    if not out.exists():
        fail("Inno Setup did not produce dist/MistuGorjetas_Setup.exe")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Build MistuGorjetas_Setup.exe")
    ap.add_argument("--keep-key", action="store_true", help="reuse the key hash already configured")
    ap.add_argument("--set-key-only", action="store_true", help="only set the key hash, do not build")
    ap.add_argument("--skip-installer", action="store_true", help="run PyInstaller only")
    ap.add_argument("--iscc", help="path to ISCC.exe (Inno Setup compiler)")
    args = ap.parse_args()

    print(f"{APP_NAME} {VERSION} - build\n")
    if args.keep_key:
        if not key_configured():
            fail("no key configured yet - run without --keep-key first")
        print("Using the key hash already configured.")
    else:
        write_key_hashes(ask_key())
    if args.set_key_only:
        return 0

    if sys.platform != "win32":
        fail("the application and installer must be built on Windows (64-bit).")

    run_pyinstaller()
    if args.skip_installer:
        print(f"\nDone: {DIST / 'MistuGorjetas'}")
        return 0
    out = run_inno(args.iscc)
    print(f"\nDone: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
